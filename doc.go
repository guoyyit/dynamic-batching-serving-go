// Package serving 提供纯进程内的多模型动态批处理推理调度能力。
//
// 语义概述（详见 docs/）：
//   - 多模型共用一个 Scheduler 入口，每个模型独立队列与批处理参数；
//   - 调度循环周期性把各模型队列组批，一个批次可混合多个模型；
//   - 等待超时与取消得到可区分结论，已组批请求不会被静默丢弃；
//   - 固定数量工作协程消费批次，每个请求恰好结算一次；
//   - 单项失败只影响单项，可重试失败按模型重试策略处理；
//   - 队列有界，满时按 reject/block 策略背压；
//   - 配置以版本快照原子热更新，并暴露队列深度/批大小/延迟指标。
